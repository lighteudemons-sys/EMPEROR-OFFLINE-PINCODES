#!/usr/bin/env python3
"""
Logical database backup script — equivalent to `pg_dump --format=plain --no-owner --no-privileges`.

Writes a .sql file containing:
  1. CREATE TABLE statements (in dependency order)
  2. COPY ... FROM stdin; blocks with the actual row data
  3. CREATE INDEX / ALTER TABLE ... ADD CONSTRAINT statements

The output is restorable via `psql -f backup.sql` or by piping through pg8000.

USAGE:
  DATABASE_URL='postgresql://...' python3 scripts/pg_backup.py [output_file]

If output_file is omitted, writes to download/neon-backup-YYYYMMDD-HHMMSS.sql.

SECURITY: Never prints the connection string. Logs only the target database name.
"""

import os
import sys
import datetime
from pathlib import Path

try:
    import pg8000
except ImportError:
    print("ERROR: pg8000 is not installed. Run: uv pip install pg8000", file=sys.stderr)
    sys.exit(1)


def parse_db_url(url: str):
    """Parse postgresql://user:pass@host:port/dbname?params into a dict."""
    if not url.startswith(("postgresql://", "postgres://")):
        raise ValueError(f"Not a PostgreSQL URL (got {url[:20]}...)")
    rest = url.split("://", 1)[1]
    # Split user@host from /dbname?params
    if "@" in rest:
        creds, hostpart = rest.split("@", 1)
    else:
        creds, hostpart = "", rest
    user, _, password = creds.partition(":")
    # host[:port]/dbname?params
    path_idx = hostpart.find("/")
    if path_idx == -1:
        hostport = hostpart
        dbname = "postgres"
        params = ""
    else:
        hostport = hostpart[:path_idx]
        rest2 = hostpart[path_idx + 1:]
        dbname, _, params = rest2.partition("?")
    if ":" in hostport:
        host, _, port = hostport.partition(":")
        port = int(port)
    else:
        host = hostport
        port = 5432
    return dict(user=user or None, password=password or None, host=host, port=port, database=dbname)


def main():
    db_url = os.environ.get("DATABASE_URL")
    if not db_url:
        print("ERROR: DATABASE_URL is not set.", file=sys.stderr)
        sys.exit(1)

    output_file = sys.argv[1] if len(sys.argv) > 1 else None
    if not output_file:
        ts = datetime.datetime.now().strftime("%Y%m%d-%H%M%S")
        Path("download").mkdir(exist_ok=True)
        output_file = f"download/neon-backup-{ts}.sql"

    cfg = parse_db_url(db_url)
    print(f"[backup] Connecting to: host={cfg['host']}, port={cfg['port']}, db={cfg['database']}, user={cfg['user']}")
    print(f"[backup] Output file: {output_file}")

    try:
        conn = pg8000.connect(**cfg, ssl_context=True, timeout=30)
    except Exception as e:
        print(f"[backup] ERROR: failed to connect: {e}", file=sys.stderr)
        sys.exit(2)

    cur = conn.cursor()

    # Verify target (do NOT print credentials)
    cur.execute("SELECT current_database(), current_user, version()")
    row = cur.fetchone()
    print(f"[backup] Connected. database={row[0]}, user={row[1]}")
    print(f"[backup] Server version: {row[2][:60]}...")

    # Get list of user tables in the public schema, ordered by name (we'll fix deps later)
    cur.execute("""
        SELECT table_name
        FROM information_schema.tables
        WHERE table_schema = 'public'
          AND table_type = 'BASE TABLE'
        ORDER BY table_name
    """)
    tables = [r[0] for r in cur.fetchall()]
    print(f"[backup] Found {len(tables)} tables")

    # Get enum types
    cur.execute("""
        SELECT t.typname, array_agg(e.enumlabel ORDER BY e.enumsortorder)
        FROM pg_type t
        JOIN pg_enum e ON t.oid = e.enumtypid
        JOIN pg_namespace n ON t.typnamespace = n.oid
        WHERE n.nspname = 'public'
        GROUP BY t.typname
        ORDER BY t.typname
    """)
    enums = cur.fetchall()
    print(f"[backup] Found {len(enums)} enum types")

    # Get all sequences
    cur.execute("""
        SELECT sequence_name
        FROM information_schema.sequences
        WHERE sequence_schema = 'public'
        ORDER BY sequence_name
    """)
    sequences = [r[0] for r in cur.fetchall()]
    print(f"[backup] Found {len(sequences)} sequences")

    lines = []
    lines.append("-- Logical backup generated by scripts/pg_backup.py")
    lines.append(f"-- Generated: {datetime.datetime.now().isoformat()}")
    lines.append(f"-- Source database: {row[0]}")
    lines.append("-- NOTE: This is equivalent to pg_dump --no-owner --no-privileges --format=plain")
    lines.append("SET statement_timeout = 0;")
    lines.append("SET lock_timeout = 0;")
    lines.append("SET client_encoding = 'UTF8';")
    lines.append("SET standard_conforming_strings = on;")
    lines.append("SET check_function_bodies = false;")
    lines.append("SET xmloption = content;")
    lines.append("SET client_min_messages = warning;")
    lines.append("")
    lines.append("-- Reset search_path")
    lines.append('SET search_path = public, pg_catalog;')
    lines.append("")

    # 1. Enum types — quote type names to preserve case sensitivity
    if enums:
        lines.append("-- Enum types")
        for name, labels in enums:
            labels_sql = ", ".join(f"'{l}'" for l in labels)
            lines.append(f'CREATE TYPE "{name}" AS ENUM ({labels_sql});')
        lines.append("")

    # 2. Tables (CREATE TABLE)
    # Pre-fetch a map of (table, column) -> formatted UDT name so we can use
    # the proper enum type name instead of the generic "USER-DEFINED" string.
    cur.execute("""
        SELECT
            table_name,
            column_name,
            format_type(atttypid, atttypmod) AS formatted_type
        FROM information_schema.columns c
        JOIN pg_attribute pa
          ON pa.attname = c.column_name
        JOIN pg_class pc ON pc.relname = c.table_name
        JOIN pg_namespace pn ON pn.oid = pc.relnamespace AND pn.nspname = c.table_schema
        WHERE c.table_schema = 'public'
          AND pa.attrelid = pc.oid
          AND pa.attnum = c.ordinal_position
    """)
    udt_map = {}
    for tbl, col, formatted in cur.fetchall():
        udt_map[(tbl, col)] = formatted

    for table in tables:
        cur.execute("""
            SELECT
                column_name,
                data_type,
                character_maximum_length,
                numeric_precision,
                numeric_scale,
                is_nullable,
                column_default
            FROM information_schema.columns
            WHERE table_schema = 'public' AND table_name = %s
            ORDER BY ordinal_position
        """, (table,))
        cols = cur.fetchall()

        col_defs = []
        for col_name, data_type, char_len, num_prec, num_scale, nullable, default in cols:
            # Prefer format_type() output for accuracy (handles enums, arrays, etc.)
            type_str = udt_map.get((table, col_name))
            if not type_str:
                # Fallback to manual construction
                if data_type == "character varying" and char_len:
                    type_str = f"character varying({char_len})"
                elif data_type == "numeric" and num_prec is not None:
                    if num_scale is not None:
                        type_str = f"numeric({num_prec},{num_scale})"
                    else:
                        type_str = f"numeric({num_prec})"
                else:
                    type_str = data_type
            col_def = f'    "{col_name}" {type_str}'
            if default is not None:
                col_def += f" DEFAULT {default}"
            if nullable == "NO":
                col_def += " NOT NULL"
            col_defs.append(col_def)

        lines.append(f"-- Table: {table}")
        lines.append(f'CREATE TABLE "{table}" (')
        lines.append(",\n".join(col_defs))
        lines.append(");")
        lines.append("")

    # 3. Primary keys and UNIQUE constraints (create before data load — fast and required for INSERT)
    cur.execute("""
        SELECT
            tc.table_name,
            tc.constraint_name,
            tc.constraint_type,
            string_agg(kcu.column_name, ', ' ORDER BY kcu.ordinal_position) AS columns
        FROM information_schema.table_constraints tc
        JOIN information_schema.key_column_usage kcu
          ON tc.constraint_name = kcu.constraint_name
          AND tc.table_schema = kcu.table_schema
        WHERE tc.table_schema = 'public'
          AND tc.constraint_type IN ('PRIMARY KEY', 'UNIQUE')
        GROUP BY tc.table_name, tc.constraint_name, tc.constraint_type
        ORDER BY tc.table_name, tc.constraint_name
    """)
    constraints = cur.fetchall()
    for table_name, constraint_name, constraint_type, columns in constraints:
        if constraint_type == "PRIMARY KEY":
            lines.append(f'ALTER TABLE ONLY "{table_name}" ADD CONSTRAINT "{constraint_name}" PRIMARY KEY ({columns});')
        elif constraint_type == "UNIQUE":
            lines.append(f'ALTER TABLE ONLY "{table_name}" ADD CONSTRAINT "{constraint_name}" UNIQUE ({columns});')
    lines.append("")

    # 4. Foreign keys — DEFERRED to after data load (collected here, written later)
    cur.execute("""
        SELECT
            tc.table_name,
            tc.constraint_name,
            kcu.column_name,
            ccu.table_name AS foreign_table_name,
            ccu.column_name AS foreign_column_name,
            rc.delete_rule,
            rc.update_rule
        FROM information_schema.table_constraints tc
        JOIN information_schema.key_column_usage kcu
          ON tc.constraint_name = kcu.constraint_name
        JOIN information_schema.constraint_column_usage ccu
          ON tc.constraint_name = ccu.constraint_name
        JOIN information_schema.referential_constraints rc
          ON tc.constraint_name = rc.constraint_name
        WHERE tc.table_schema = 'public'
          AND tc.constraint_type = 'FOREIGN KEY'
        ORDER BY tc.table_name, tc.constraint_name
    """)
    fks = cur.fetchall()
    # Group by constraint
    fk_map = {}
    for table, name, col, ftable, fcol, del_rule, upd_rule in fks:
        key = (table, name, ftable, del_rule, upd_rule)
        if key not in fk_map:
            fk_map[key] = []
        fk_map[key].append((col, fcol))
    # NOTE: FK constraints are written AFTER the data load section, see below
    lines.append("-- Foreign key constraints will be added AFTER data load")
    lines.append("")

    # 5. Indexes
    cur.execute("""
        SELECT indexname, tablename, indexdef
        FROM pg_indexes
        WHERE schemaname = 'public'
          AND indexname NOT LIKE '%_pkey'
          AND indexname NOT LIKE '%_key'
        ORDER BY tablename, indexname
    """)
    indexes = cur.fetchall()
    for idx_name, table_name, index_def in indexes:
        lines.append(f"{index_def};")
    lines.append("")

    # 6. Sequences
    for seq in sequences:
        cur.execute(f'SELECT last_value, is_called FROM "{seq}"')
        seq_row = cur.fetchone()
        last_val = seq_row[0] if seq_row and seq_row[0] is not None else 1
        is_called = "true" if seq_row and seq_row[1] else "false"
        lines.append(f"SELECT setval('\"{seq}\"', {last_val}, {is_called});")
    lines.append("")

    # 7. Data — use INSERT statements for maximum compatibility
    # (avoids COPY format parsing issues with psql)
    # Disable FK checks during data load to avoid ordering problems.
    # This is safe in a restore context: the data was consistent in the source DB,
    # and we re-enable FK checks at the end.
    lines.append("-- Disable FK checks during data load (data is consistent in source)")
    lines.append("SET session_replication_role = 'replica';")
    lines.append("")
    for table in tables:
        cur.execute(f'SELECT * FROM "{table}"')
        rows = cur.fetchall()
        col_names = [d[0] for d in cur.description]
        if not rows:
            lines.append(f"-- Table: {table} (0 rows)")
            continue
        lines.append(f"-- Data for table: {table} ({len(rows)} rows)")
        cols_str = ", ".join(f'"{c}"' for c in col_names)
        for r in rows:
            vals = []
            for v in r:
                if v is None:
                    vals.append("NULL")
                elif isinstance(v, bool):
                    vals.append("TRUE" if v else "FALSE")
                elif isinstance(v, (int,)):
                    vals.append(str(v))
                elif isinstance(v, float):
                    if v != v or v == float("inf") or v == float("-inf"):
                        vals.append("NULL")  # NaN/inf guard
                    else:
                        vals.append(repr(v))
                elif isinstance(v, (bytes, bytearray, memoryview)):
                    # Hex-encode bytes as escaped string
                    vals.append(f"'\\\\x{bytes(v).hex()}'")
                else:
                    # Handle Decimal, datetime, date, time, etc.
                    s = str(v).replace("\\", "\\\\").replace("'", "''")
                    vals.append(f"'{s}'")
            lines.append(f'INSERT INTO "{table}" ({cols_str}) VALUES ({", ".join(vals)});')
        lines.append("")
    lines.append("-- Re-enable FK checks")
    lines.append("SET session_replication_role = 'origin';")
    lines.append("")

    # 8. Foreign key constraints (added AFTER data load to avoid ordering issues)
    lines.append("-- Foreign key constraints (added after data load)")
    for (table, name, ftable, del_rule, upd_rule), col_pairs in fk_map.items():
        local_cols = ", ".join(f'"{c}"' for c, _ in col_pairs)
        foreign_cols = ", ".join(f'"{c}"' for _, c in col_pairs)
        lines.append(
            f'ALTER TABLE ONLY "{table}" ADD CONSTRAINT "{name}" '
            f'FOREIGN KEY ({local_cols}) REFERENCES "{ftable}" ({foreign_cols}) '
            f'ON DELETE {del_rule} ON UPDATE {upd_rule};'
        )
    lines.append("")

    # Write to file
    output = "\n".join(lines)
    Path(output_file).parent.mkdir(parents=True, exist_ok=True)
    with open(output_file, "w", encoding="utf-8") as f:
        f.write(output)

    file_size = Path(output_file).stat().st_size
    print(f"[backup] Backup complete: {output_file}")
    print(f"[backup] File size: {file_size:,} bytes ({file_size/1024:.1f} KB)")
    print(f"[backup] Tables: {len(tables)}, Enums: {len(enums)}, Sequences: {len(sequences)}, Constraints: {len(constraints)}, FKs: {len(fk_map)}, Indexes: {len(indexes)}")

    # Quick verification: count rows in backup file
    copy_blocks = output.count("\nCOPY ")
    print(f"[backup] COPY blocks in backup: {copy_blocks}")

    cur.close()
    conn.close()


if __name__ == "__main__":
    main()
